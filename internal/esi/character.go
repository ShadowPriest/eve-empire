// Summary is the compact per-character view for the overview page.
type Summary struct {
	Wallet      float64
	TotalSP     int64
	SolarSystem string
	Location    string // station/structure name when docked, "" in space
	Ship        string
	ShipName    string
	Online      bool
	QueueSkill  string // currently training skill, "" if queue empty
	QueueLevel  int
	QueueEnds   time.Time
	Errors      []string
}

func (c *Client) Summary(characterID int64) Summary {
	var s Summary

	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/wallet/", characterID), &s.Wallet); err != nil {
		s.Errors = append(s.Errors, fmt.Sprintf("wallet: %v", err))
	}

	var skills struct {
		TotalSP int64 `json:"total_sp"`
	}
	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/skills/", characterID), &skills); err != nil {
		s.Errors = append(s.Errors, fmt.Sprintf("skills: %v", err))
	}
	s.TotalSP = skills.TotalSP

	var loc struct {
		SolarSystemID int64 `json:"solar_system_id"`
		StationID     int64 `json:"station_id"`
		StructureID   int64 `json:"structure_id"`
	}
	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/location/", characterID), &loc); err != nil {
		s.Errors = append(s.Errors, fmt.Sprintf("location: %v", err))
	}

	var ship struct {
		ShipTypeID int64  `json:"ship_type_id"`
		ShipName   string `json:"ship_name"`
	}
	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/ship/", characterID), &ship); err != nil {
		s.Errors = append(s.Errors, fmt.Sprintf("ship: %v", err))
	}
	s.ShipName = cleanPyString(ship.ShipName)

	var online struct {
		Online bool `json:"online"`
	}
	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/online/", characterID), &online); err != nil {
		s.Errors = append(s.Errors, fmt.Sprintf("online: %v", err))
	}
	s.Online = online.Online

	queue, err := c.SkillQueue(characterID)
	if err != nil {
		s.Errors = append(s.Errors, fmt.Sprintf("queue: %v", err))
	}
	now := time.Now()
	for _, q := range queue {
		if q.FinishDate.After(now) {
			s.QueueSkill = q.SkillName
			s.QueueLevel = q.FinishedLevel
			s.QueueEnds = q.FinishDate
			break
		}
	}

	ids := []int64{loc.SolarSystemID, ship.ShipTypeID}
	if loc.StationID != 0 {
		ids = append(ids, loc.StationID)
	}
	names := c.Names(ids)
	s.SolarSystem = names[loc.SolarSystemID]
	s.Ship = names[ship.ShipTypeID]
	switch {
	case loc.StationID != 0:
		s.Location = names[loc.StationID]
	case loc.StructureID != 0:
		// structures never resolve via /universe/names/ — authorized endpoint only
		var st struct {
			Name string `json:"name"`
		}
		if _, err := c.get(characterID, fmt.Sprintf("/universe/structures/%d/", loc.StructureID), &st); err == nil && st.Name != "" {
			s.Location = st.Name
		} else {
			s.Location = fmt.Sprintf("Структура %d", loc.StructureID)
		}
	}
	return s
}

// Online reports whether the character is currently logged in.
