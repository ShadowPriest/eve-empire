type QueueEntry struct {
	SkillID         int64     `json:"skill_id"`
	SkillName       string    `json:"-"`
	FinishedLevel   int       `json:"finished_level"`
	FinishDate      time.Time `json:"finish_date"`
	StartDate       time.Time `json:"start_date"`
	Position        int       `json:"queue_position"`
	TrainingStartSP int64     `json:"training_start_sp"`
	LevelStartSP    int64     `json:"level_start_sp"`
	LevelEndSP      int64     `json:"level_end_sp"`
}

func (c *Client) SkillQueue(characterID int64) ([]QueueEntry, error) {
	var queue []QueueEntry
	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/skillqueue/", characterID), &queue); err != nil {
		return nil, err
	}
	ids := make([]int64, len(queue))
	for i, q := range queue {
		ids[i] = q.SkillID
	}
	names := c.typeNamesLocalized(ids)
	for i := range queue {
		queue[i].SkillName = names[queue[i].SkillID]
	}
	return queue, nil
}

// Skill is one entry of the full character skill sheet.
type Skill struct {
	SkillID      int64  `json:"skill_id"`
	SkillName    string `json:"-"`
	ActiveLevel  int    `json:"active_skill_level"`
	TrainedLevel int    `json:"trained_skill_level"`
	Skillpoints  int64  `json:"skillpoints_in_skill"`
}

type SkillSheet struct {
	Skills        []Skill `json:"skills"`
	TotalSP       int64   `json:"total_sp"`
	UnallocatedSP int64   `json:"unallocated_sp"`
}

// Skills returns the full skill list with resolved names, sorted by name.
func (c *Client) Skills(characterID int64) (*SkillSheet, error) {
	var sheet SkillSheet
	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/skills/", characterID), &sheet); err != nil {
		return nil, err
	}
	ids := make([]int64, len(sheet.Skills))
	for i, s := range sheet.Skills {
		ids[i] = s.SkillID
	}
	names := c.typeNamesLocalized(ids)
	for i := range sheet.Skills {
		sheet.Skills[i].SkillName = names[sheet.Skills[i].SkillID]
	}
	sort.Slice(sheet.Skills, func(i, j int) bool {
		return sheet.Skills[i].SkillName < sheet.Skills[j].SkillName
	})
	return &sheet, nil
}

// TreeSkill is one skill inside a group tree: trained by the character
// (Known) or merely existing in game.
type TreeSkill struct {
	Skill
	Known bool
}

// SkillGroupTree is one in-game skill group with every published skill
// in it; the character's trained ones are marked Known.
type SkillGroupTree struct {
	Name    string
	Skills  []TreeSkill
	Known   int
	GroupSP int64
}

const skillCategoryID = 16

// typeInfo is the localized subset of /universe/types/{id}/.
type typeInfo struct {
	Name      string `json:"name"`
	Published bool   `json:"published"`
}

// typeInfos resolves type name + published per id via /universe/types/
// — unlike the batch /universe/names/ this endpoint is localized.
// Failures are simply absent from the result (callers fall back to the
// batch resolver). Static data: cached per language after first load.
func (c *Client) typeInfos(ids []int64) map[int64]typeInfo {
	out := make(map[int64]typeInfo, len(ids))
	var mu sync.Mutex
	sem := make(chan struct{}, 8)
	var wg sync.WaitGroup
	for _, id := range dedupe(ids) {
		if id == 0 {
			continue
		}
		wg.Add(1)
		go func(id int64) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			var ti typeInfo
			if _, err := c.get(0, fmt.Sprintf("/universe/types/%d/", id), &ti); err == nil {
				mu.Lock()
				out[id] = ti
				mu.Unlock()
			}
		}(id)
	}
	wg.Wait()
	return out
}

// typeNamesLocalized names the given type ids via typeInfos, falling
// back to the English batch resolver for anything that failed.
func (c *Client) typeNamesLocalized(ids []int64) map[int64]string {
	out := make(map[int64]string, len(ids))
	var missing []int64
	for id, ti := range c.typeInfos(ids) {
		if ti.Name != "" {
			out[id] = ti.Name
		}
	}
	for _, id := range dedupe(ids) {
		if _, ok := out[id]; !ok && id != 0 {
			missing = append(missing, id)
		}
	}
	if len(missing) > 0 {
		for id, n := range c.Names(missing) {
			out[id] = n
		}
	}
	return out
}

// SkillTree groups the character's trained skills by in-game skill
// group (universe category 16). Group composition is static and cached.
func (c *Client) SkillTree(sheet *SkillSheet) ([]SkillGroupTree, error) {
	var cat struct {
		Groups []int64 `json:"groups"`
	}
	if _, err := c.get(0, fmt.Sprintf("/universe/categories/%d/", skillCategoryID), &cat); err != nil {
		return nil, err
	}

	type groupInfo struct {
		ID    int64
		Name  string  `json:"name"`
		Types []int64 `json:"types"`
	}
	infos := make([]groupInfo, len(cat.Groups))
	sem := make(chan struct{}, 8)
	var wg sync.WaitGroup
	for i, gid := range cat.Groups {
		wg.Add(1)
		go func(i int, gid int64) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			var gi groupInfo
			if _, err := c.get(0, fmt.Sprintf("/universe/groups/%d/", gid), &gi); err == nil {
				gi.ID = gid
				infos[i] = gi
			}
		}(i, gid)
	}
	wg.Wait()

	byType := map[int64]Skill{}
	for _, s := range sheet.Skills {
		byType[s.SkillID] = s
	}

	// Skills the character hasn't injected: resolve name + published flag
	// per type. Static data — after the first load it lives in the cache.
	var unknownIDs []int64
	for _, gi := range infos {
		for _, tid := range gi.Types {
			if _, ok := byType[tid]; !ok {
				unknownIDs = append(unknownIDs, tid)
			}
		}
	}
	unknown := c.typeInfos(unknownIDs)

	var tree []SkillGroupTree
	for _, gi := range infos {
		if gi.Name == "" {
			continue
		}
		node := SkillGroupTree{Name: gi.Name}
		for _, tid := range gi.Types {
			if s, ok := byType[tid]; ok {
				node.Skills = append(node.Skills, TreeSkill{Skill: s, Known: true})
				node.Known++
				node.GroupSP += s.Skillpoints
			} else if ti, ok := unknown[tid]; ok && ti.Published {
				node.Skills = append(node.Skills, TreeSkill{Skill: Skill{SkillID: tid, SkillName: ti.Name}})
			}
		}
		if len(node.Skills) > 0 {
			sort.Slice(node.Skills, func(i, j int) bool {
				return node.Skills[i].SkillName < node.Skills[j].SkillName
			})
			tree = append(tree, node)
		}
	}
	sort.Slice(tree, func(i, j int) bool { return tree[i].Name < tree[j].Name })
	return tree, nil
}

// ── blueprints owned by a character ──────────────────────────────────

// OwnedBlueprint is one blueprint stack in a hangar, with the research
// levels of that particular item.
type OwnedBlueprint struct {
	ItemID     int64  `json:"item_id"`
	TypeID     int64  `json:"type_id"`
	TypeName   string `json:"-"`
	LocationID int64  `json:"location_id"`
	Location   string `json:"-"`
	// quantity: -1 = original, -2 = copy, positive = stack of copies
	Quantity int64 `json:"quantity"`
	Runs     int64 `json:"runs"` // -1 for originals
	ME       int   `json:"material_efficiency"`
	TE       int   `json:"time_efficiency"`
}

// IsCopy reports whether this is a blueprint copy.
func (b *OwnedBlueprint) IsCopy() bool { return b.Quantity == -2 || b.Runs > 0 }

// CharacterBlueprints lists every blueprint the character owns
// (scope esi-characters.read_blueprints.v1), with names and locations.
func (c *Client) CharacterBlueprints(characterID int64) ([]OwnedBlueprint, error) {
	var all []OwnedBlueprint
	page := 1
	for {
		var chunk []OwnedBlueprint
		pages, err := c.get(characterID,
			fmt.Sprintf("/characters/%d/blueprints/?page=%d", characterID, page), &chunk)
		if err != nil {
			return nil, err
		}
		all = append(all, chunk...)
		if page >= pages {
			break
		}
		page++
	}

	typeIDs := make([]int64, 0, len(all))
	locIDs := make([]int64, 0, len(all))
	for _, b := range all {
		typeIDs = append(typeIDs, b.TypeID)
		locIDs = append(locIDs, b.LocationID)
	}
	names := c.typeNamesLocalized(typeIDs)
	locs := c.LocationNames(characterID, locIDs)
	for i := range all {
		all[i].TypeName = names[all[i].TypeID]
		if n := locs[all[i].LocationID]; n != "" {
			all[i].Location = n
		} else {
			// Blueprints inside containers/ships report that item as location.
			all[i].Location = "в контейнере"
		}
	}
	sort.Slice(all, func(i, j int) bool { return all[i].TypeName < all[j].TypeName })
	return all, nil
}

