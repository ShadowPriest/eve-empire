// CorporationProjects fetches all corporation projects. The endpoint
// only exists on the new compatibility-dated ESI. The listing is
// cursor-paginated (10 per page, oldest first) and defaults to active
// projects only, so we ask for state=All and walk the "after" cursor;
// the schema is still evolving, so items are decoded generically.
func (c *Client) CorporationProjects(characterID, corporationID int64) ([]map[string]any, error) {
	toList := func(v any) []map[string]any {
		list, ok := v.([]any)
		if !ok {
			return nil
		}
		var out []map[string]any
		for _, item := range list {
			if m, ok := item.(map[string]any); ok {
				out = append(out, m)
			}
		}
		return out
	}

	var merged []map[string]any
	seen := map[string]bool{}
	query := "?state=All"
	for page := 0; page < 50; page++ { // safety cap
		var raw any
		if _, err := c.getCompat(characterID,
			fmt.Sprintf("/corporations/%d/projects%s", corporationID, query), &raw); err != nil {
			if page == 0 {
				return nil, err
			}
			log.Printf("corp projects page %d: %v", page, err)
			break
		}

		m, ok := raw.(map[string]any)
		if !ok {
			// Plain array (older schema) — single page.
			merged = append(merged, toList(raw)...)
			break
		}

		added := 0
		for _, p := range toList(m["projects"]) {
			key := fmt.Sprint(p["id"]) + "/" + fmt.Sprint(p["name"])
			if !seen[key] {
				seen[key] = true
				merged = append(merged, p)
				added++
			}
		}

		cursor, _ := m["cursor"].(map[string]any)
		after, _ := cursor["after"].(string)
		if after == "" || added == 0 {
			break
		}
		query = "?state=All&after=" + url.QueryEscape(after)
	}

	// Newest first for display (RFC3339 sorts lexicographically).
	sort.Slice(merged, func(i, j int) bool {
		return fmt.Sprint(merged[i]["last_modified"]) > fmt.Sprint(merged[j]["last_modified"])
	})
	return merged, nil
}

