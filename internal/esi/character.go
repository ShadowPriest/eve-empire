// ── assets ───────────────────────────────────────────────────────────

type rawAsset struct {
	ItemID     int64 `json:"item_id"`
	TypeID     int64 `json:"type_id"`
	LocationID int64 `json:"location_id"`
	Quantity   int64 `json:"quantity"`
	// ESI only sets this flag for blueprint copies.
	IsBlueprintCopy bool `json:"is_blueprint_copy"`
}

type AssetItem struct {
	TypeID   int64
	TypeName string
	Quantity int64
	IsCopy   bool // blueprint copy — needs the "bpc" artwork
	// Research levels, filled in for blueprints so the item card opens
	// with the real numbers of that stack.
	ME   int
	TE   int
	Runs int64 // -1 for originals
}

type LocationAssets struct {
	LocationID   int64
	LocationName string
	Total        int64
	Items        []AssetItem
}

func (c *Client) assetPages(characterID int64, pathFmt string) ([]rawAsset, error) {
	var all []rawAsset
	page := 1
	for {
		var chunk []rawAsset
		pages, err := c.get(characterID, fmt.Sprintf(pathFmt, page), &chunk)
		if err != nil {
			return nil, err
		}
		all = append(all, chunk...)
		if page >= pages {
			return all, nil
		}
		page++
	}
}

// groupAssets rolls nested items (containers, ship holds) up to their
// real root location and aggregates quantities by type. bpByItem adds
// per-item blueprint research levels (may be nil).
func (c *Client) groupAssets(characterID int64, raw []rawAsset, bpByItem map[int64]OwnedBlueprint) []LocationAssets {
	byItem := map[int64]rawAsset{}
	for _, a := range raw {
		byItem[a.ItemID] = a
	}
	rootOf := func(a rawAsset) int64 {
		loc := a.LocationID
		for depth := 0; depth < 32; depth++ {
			parent, ok := byItem[loc]
			if !ok {
				return loc
			}
			loc = parent.LocationID
		}
		return loc
	}

	// Blueprints are grouped by their research levels too: copies and
	// originals, and differently researched stacks, are distinct items.
	type assetKey struct {
		typeID int64
		isCopy bool
		me, te int
		runs   int64
	}
	counts := map[int64]map[assetKey]int64{} // root location -> key -> qty
	for _, a := range raw {
		root := rootOf(a)
		if counts[root] == nil {
			counts[root] = map[assetKey]int64{}
		}
		qty := a.Quantity
		if qty == 0 {
			qty = 1
		}
		k := assetKey{typeID: a.TypeID, isCopy: a.IsBlueprintCopy, runs: -1}
		if bp, ok := bpByItem[a.ItemID]; ok {
			k.me, k.te, k.runs, k.isCopy = bp.ME, bp.TE, bp.Runs, bp.IsCopy()
		}
		counts[root][k] += qty
	}

	// Resolve names: types + station/system locations via /universe/names/,
	// structures via the authed structures endpoint.
	var nameIDs []int64
	structIDs := map[int64]string{}
	for loc, types := range counts {
		if loc >= 1_000_000_000_000 {
			structIDs[loc] = ""
		} else {
			nameIDs = append(nameIDs, loc)
		}
		for k := range types {
			nameIDs = append(nameIDs, k.typeID)
		}
	}
	names := c.Names(nameIDs)
	for sid := range structIDs {
		var st struct {
			Name string `json:"name"`
		}
		if _, err := c.get(characterID, fmt.Sprintf("/universe/structures/%d/", sid), &st); err == nil && st.Name != "" {
			structIDs[sid] = st.Name
		} else {
			structIDs[sid] = fmt.Sprintf("Структура %d", sid)
		}
	}

	var out []LocationAssets
	for loc, types := range counts {
		la := LocationAssets{LocationID: loc}
		if loc >= 1_000_000_000_000 {
			la.LocationName = structIDs[loc]
		} else if n := names[loc]; n != "" {
			la.LocationName = n
		} else {
			la.LocationName = fmt.Sprintf("Локация %d", loc)
		}
		for k, q := range types {
			name := names[k.typeID]
			if name == "" {
				name = fmt.Sprintf("Тип %d", k.typeID)
			}
			la.Items = append(la.Items, AssetItem{
				TypeID: k.typeID, TypeName: name, Quantity: q, IsCopy: k.isCopy,
				ME: k.me, TE: k.te, Runs: k.runs,
			})
			la.Total += q
		}
		sort.Slice(la.Items, func(i, j int) bool {
			if la.Items[i].Quantity != la.Items[j].Quantity {
				return la.Items[i].Quantity > la.Items[j].Quantity
			}
			return la.Items[i].TypeName < la.Items[j].TypeName
		})
		out = append(out, la)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Total > out[j].Total })
	return out
}

// CharacterAssets returns the character's assets grouped by location,
// with blueprint research levels merged in.
func (c *Client) CharacterAssets(characterID int64) ([]LocationAssets, error) {
	raw, err := c.assetPages(characterID, fmt.Sprintf("/characters/%d/assets/?page=%%d", characterID))
	if err != nil {
		return nil, err
	}
	bpByItem := map[int64]OwnedBlueprint{}
	if bps, err := c.CharacterBlueprints(characterID); err == nil {
		for _, b := range bps {
			bpByItem[b.ItemID] = b
		}
	}
	return c.groupAssets(characterID, raw, bpByItem), nil
}

