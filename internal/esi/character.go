// MarketOrdersAt returns the live order book for a type at the given
// station or structure. Stations resolve through their region market;
// structures use the authenticated structure market endpoint.
func (c *Client) MarketOrdersAt(characterID, typeID, locationID int64) (*MarketDepth, error) {
	type rawOrder struct {
		OrderID      int64   `json:"order_id"`
		Price        float64 `json:"price"`
		VolumeRemain int64   `json:"volume_remain"`
		IsBuyOrder   bool    `json:"is_buy_order"`
		LocationID   int64   `json:"location_id"`
		TypeID       int64   `json:"type_id"`
	}
	var raw []rawOrder

	if locationID >= 1_000_000_000_000 {
		// Player structure market (paginated, authenticated).
		page := 1
		for {
			var chunk []rawOrder
			pages, err := c.get(characterID,
				fmt.Sprintf("/markets/structures/%d/?page=%d", locationID, page), &chunk)
			if err != nil {
				return nil, err
			}
			for _, o := range chunk {
				if o.TypeID == typeID {
					raw = append(raw, o)
				}
			}
			if page >= pages {
				break
			}
			page++
		}
	} else {
		regionID, err := c.regionOfStation(locationID)
		if err != nil {
			return nil, err
		}
		page := 1
		for {
			var chunk []rawOrder
			pages, err := c.get(0,
				fmt.Sprintf("/markets/%d/orders/?order_type=all&type_id=%d&page=%d", regionID, typeID, page), &chunk)
			if err != nil {
				return nil, err
			}
			for _, o := range chunk {
				if o.LocationID == locationID {
					raw = append(raw, o)
				}
			}
			if page >= pages {
				break
			}
			page++
		}
	}

	depth := &MarketDepth{}
	for _, o := range raw {
		d := DepthOrder{OrderID: o.OrderID, Price: o.Price, VolumeRemain: o.VolumeRemain}
		if o.IsBuyOrder {
			depth.Buys = append(depth.Buys, d)
		} else {
			depth.Sells = append(depth.Sells, d)
		}
	}
	sort.Slice(depth.Sells, func(i, j int) bool { return depth.Sells[i].Price < depth.Sells[j].Price })
	sort.Slice(depth.Buys, func(i, j int) bool { return depth.Buys[i].Price > depth.Buys[j].Price })
	return depth, nil
}

