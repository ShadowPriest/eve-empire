// AssetCount fetches all asset pages and returns the total item count.
func (c *Client) AssetCount(characterID int64) (int, error) {
	total := 0
	page := 1
	for {
		var assets []struct {
			ItemID int64 `json:"item_id"`
		}
		pages, err := c.get(characterID, fmt.Sprintf("/characters/%d/assets/?page=%d", characterID, page), &assets)
		if err != nil {
			return total, err
		}
		total += len(assets)
		if page >= pages {
			return total, nil
		}
		page++
	}
}
