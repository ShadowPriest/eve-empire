// LocationNames resolves station and structure ids to names: stations
// go through the public batch resolver, structures (id ≥ 1e12) need the
// authorized per-structure endpoint.
func (c *Client) LocationNames(characterID int64, ids []int64) map[int64]string {
	out := map[int64]string{}
	var stations []int64
	for _, id := range dedupe(ids) {
		if id == 0 {
			continue
		}
		if id >= 1_000_000_000_000 {
			var st struct {
				Name string `json:"name"`
			}
			if _, err := c.get(characterID, fmt.Sprintf("/universe/structures/%d/", id), &st); err == nil && st.Name != "" {
				out[id] = st.Name
			} else {
				out[id] = fmt.Sprintf("Структура %d", id)
			}
		} else {
			stations = append(stations, id)
		}
	}
	for id, n := range c.Names(stations) {
		out[id] = n
	}
	return out
}

