// cleanPyString fixes CCP's autogenerated ship names which arrive as a
// Python repr: u'Capsule\xa0— Pilot Name'.
func cleanPyString(s string) string {
	if !strings.HasPrefix(s, "u'") || !strings.HasSuffix(s, "'") || len(s) < 3 {
		return s
	}
	inner := s[2 : len(s)-1]
	var b strings.Builder
	for i := 0; i < len(inner); {
		if inner[i] != '\\' || i+1 >= len(inner) {
			b.WriteByte(inner[i])
			i++
			continue
		}
		switch inner[i+1] {
		case 'x':
			if i+4 <= len(inner) {
				if n, err := strconv.ParseUint(inner[i+2:i+4], 16, 32); err == nil {
					b.WriteRune(rune(n))
					i += 4
					continue
				}
			}
		case 'u':
			if i+6 <= len(inner) {
				if n, err := strconv.ParseUint(inner[i+2:i+6], 16, 32); err == nil {
					b.WriteRune(rune(n))
					i += 6
					continue
				}
			}
		case '\\', '\'':
			b.WriteByte(inner[i+1])
			i += 2
			continue
		}
		b.WriteByte(inner[i])
		i++
	}
	return b.String()
}

