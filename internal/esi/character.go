// Colony is one planetary colony from /characters/{id}/planets/.
type Colony struct {
	LastUpdate    time.Time `json:"last_update"`
	NumPins       int       `json:"num_pins"`
	OwnerID       int64     `json:"owner_id"`
	PlanetID      int64     `json:"planet_id"`
	PlanetType    string    `json:"planet_type"`
	SolarSystemID int64     `json:"solar_system_id"`
	UpgradeLevel  int       `json:"upgrade_level"`
	// filled in by the caller
	PlanetName string `json:"-"`
	SystemName string `json:"-"`
}

func (c *Client) Colonies(characterID int64) ([]Colony, error) {
	var out []Colony
	if _, err := c.get(characterID, fmt.Sprintf("/characters/%d/planets/", characterID), &out); err != nil {
		return nil, err
	}
	// Planet ids are NOT resolvable through /universe/names/ — including
	// one poisons the whole batch — so names come from the per-planet
	// endpoint while systems go through the batch resolver.
	sysIDs := make([]int64, 0, len(out))
	for _, col := range out {
		sysIDs = append(sysIDs, col.SolarSystemID)
	}
	names := c.Names(sysIDs)

	var wg sync.WaitGroup
	for i := range out {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			var p struct {
				Name string `json:"name"`
			}
			if _, err := c.get(0, fmt.Sprintf("/universe/planets/%d/", out[i].PlanetID), &p); err == nil {
				out[i].PlanetName = p.Name
			}
		}(i)
	}
	wg.Wait()

	for i := range out {
		out[i].SystemName = names[out[i].SolarSystemID]
		if out[i].PlanetName == "" {
			out[i].PlanetName = fmt.Sprintf("Планета %d", out[i].PlanetID)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].PlanetName < out[j].PlanetName })
	return out, nil
}

