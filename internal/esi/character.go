// fillJobNames resolves blueprint/product/facility names and the
// activity label. Structure names need the authed structures endpoint —
// /universe/names/ rejects structure ids.
func (c *Client) fillJobNames(characterID int64, jobs []*IndustryJob) {
	var ids []int64
	structIDs := map[int64]string{}
	for _, j := range jobs {
		ids = append(ids, j.BlueprintType, j.ProductTypeID)
		if j.FacilityID >= 1_000_000_000_000 {
			structIDs[j.FacilityID] = ""
		} else {
			ids = append(ids, j.FacilityID)
		}
	}
	names := c.Names(ids)

	for sid := range structIDs {
		var st struct {
			Name string `json:"name"`
		}
		if _, err := c.get(characterID, fmt.Sprintf("/universe/structures/%d/", sid), &st); err == nil && st.Name != "" {
			structIDs[sid] = st.Name
		} else {
			structIDs[sid] = fmt.Sprintf("Структура %d", sid)
		}
	}

	for _, j := range jobs {
		j.BlueprintName = names[j.BlueprintType]
		j.ProductName = names[j.ProductTypeID]
		if j.FacilityID >= 1_000_000_000_000 {
			j.Facility = structIDs[j.FacilityID]
		} else {
			j.Facility = names[j.FacilityID]
		}
		j.Activity = activityNames[j.ActivityID]
		if j.Activity == "" {
			j.Activity = fmt.Sprintf("Активность %d", j.ActivityID)
		}
	}
}

